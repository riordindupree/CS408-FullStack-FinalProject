  @BeforeEach
  void createAccountTables() {
    jdbcTemplate.execute("DROP TABLE IF EXISTS GAINED_ITEM");
    jdbcTemplate.execute("DROP TABLE IF EXISTS GAINED_MONSTER");
    jdbcTemplate.execute("DROP TABLE IF EXISTS ACCOUNT_RESERVATION");
    jdbcTemplate.execute("DROP TABLE IF EXISTS PLAYER CASCADE");
    jdbcTemplate.execute("DROP TABLE IF EXISTS RUN");
    jdbcTemplate.execute("DROP TABLE IF EXISTS ITEM");
    jdbcTemplate.execute("DROP TABLE IF EXISTS MONSTER");
    jdbcTemplate.execute(
        "CREATE TABLE PLAYER (player_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "password_hash VARCHAR(255) NOT NULL, number_of_runs INTEGER NOT NULL DEFAULT 0, "
            + "high_score_run_id INTEGER UNIQUE)");
    jdbcTemplate.execute(
        "CREATE TABLE ACCOUNT_RESERVATION (player_id INTEGER PRIMARY KEY, "
            + "reservation_token VARCHAR(36) NOT NULL UNIQUE, "
            + "created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, "
            + "FOREIGN KEY (player_id) REFERENCES PLAYER(player_id) ON DELETE CASCADE)");
    jdbcTemplate.execute(
        "CREATE TABLE RUN (run_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "player_id INTEGER, steps INTEGER NOT NULL, score INTEGER NOT NULL, "
            + "korokorobi BOOLEAN, CONSTRAINT uq_run_player_run UNIQUE (player_id, run_id), "
            + "FOREIGN KEY (player_id) REFERENCES PLAYER(player_id))");
    jdbcTemplate.execute(
        "ALTER TABLE PLAYER ADD CONSTRAINT fk_player_high_score_run "
            + "FOREIGN KEY (player_id, high_score_run_id) REFERENCES RUN(player_id, run_id)");
    jdbcTemplate.execute("CREATE TABLE ITEM (item_id INTEGER PRIMARY KEY)");
    jdbcTemplate.execute("CREATE TABLE MONSTER (monster_id INTEGER PRIMARY KEY)");
    jdbcTemplate.execute(
        "CREATE TABLE GAINED_ITEM (item_id INTEGER NOT NULL, run_id INTEGER NOT NULL, "
            + "amount INTEGER NOT NULL, PRIMARY KEY (item_id, run_id), "
            + "FOREIGN KEY (item_id) REFERENCES ITEM(item_id), "
            + "FOREIGN KEY (run_id) REFERENCES RUN(run_id))");
    jdbcTemplate.execute(
        "CREATE TABLE GAINED_MONSTER (monster_id INTEGER NOT NULL, run_id INTEGER NOT NULL, "
            + "amount INTEGER NOT NULL, PRIMARY KEY (monster_id, run_id), "
            + "FOREIGN KEY (monster_id) REFERENCES MONSTER(monster_id), "
            + "FOREIGN KEY (run_id) REFERENCES RUN(run_id))");
    jdbcTemplate.update("INSERT INTO ITEM (item_id) VALUES (1)");
    jdbcTemplate.update("INSERT INTO MONSTER (monster_id) VALUES (2)");
  }

  @Test
  void createsHashedAccountAndSavesRunWithInventory() {
    int playerId = accountService.createAccountAndSaveRun(
        "correct horse battery staple",
        72,
        314,
        true,
        new int[] {1, 1, -2, 0});

    String passwordHash = jdbcTemplate.queryForObject(
        "SELECT password_hash FROM PLAYER WHERE player_id = ?",
        String.class,
        playerId);
    int runId = jdbcTemplate.queryForObject(
        "SELECT run_id FROM RUN WHERE player_id = ?",
        Integer.class,
        playerId);

    assertNotEquals("correct horse battery staple", passwordHash);
    assertTrue(passwordHash.startsWith("pbkdf2-sha256$"));
    assertTrue(accountService.authenticate(playerId, "correct horse battery staple"));
    assertFalse(accountService.authenticate(playerId, "incorrect password"));
    assertEquals(1, jdbcTemplate.queryForObject(
        "SELECT number_of_runs FROM PLAYER WHERE player_id = ?",
        Integer.class,
        playerId));
    assertEquals(314, jdbcTemplate.queryForObject(
        "SELECT score FROM RUN WHERE run_id = ?",
        Integer.class,
        runId));
    assertEquals(72, jdbcTemplate.queryForObject(
        "SELECT steps FROM RUN WHERE run_id = ?",
        Integer.class,
        runId));
    assertTrue(jdbcTemplate.queryForObject(
        "SELECT korokorobi FROM RUN WHERE run_id = ?",
        Boolean.class,
        runId));
    assertEquals(2, jdbcTemplate.queryForObject(
        "SELECT amount FROM GAINED_ITEM WHERE item_id = 1 AND run_id = ?",
        Integer.class,
        runId));
    assertEquals(1, jdbcTemplate.queryForObject(
        "SELECT amount FROM GAINED_MONSTER WHERE monster_id = 2 AND run_id = ?",
        Integer.class,
        runId));
    assertEquals(runId, jdbcTemplate.queryForObject(
        "SELECT high_score_run_id FROM PLAYER WHERE player_id = ?",
        Integer.class,
        playerId));
  }

  @Test
  void endOfRunOffersAccountCreationAndSavesTheRun() throws Exception {
    MvcResult completedRun = mvc.perform(post("/start/room-selection").param("option", "3"))
        .andExpect(status().is3xxRedirection())
        .andExpect(org.springframework.test.web.servlet.result.MockMvcResultMatchers
            .redirectedUrl("/run/complete"))
        .andReturn();
    MockHttpSession session = (MockHttpSession) completedRun.getRequest().getSession(false);

    mvc.perform(get("/run/complete").session(session))
        .andExpect(status().isOk())
        .andExpect(content().string(containsString("Add Run To Existing Account")))
        .andExpect(content().string(containsString("Create New Account")));
    mvc.perform(get("/login"))
        .andExpect(status().isOk())
        .andExpect(content().string(containsString("Player ID:")))
        .andExpect(content().string(containsString("Password:")))
        .andExpect(content().string(containsString(
            "Your Account ID is assigned when you create an account")))
        .andExpect(content().string(not(containsString("Warning:"))));
    mvc.perform(post("/run/complete/create").session(session))
        .andExpect(status().is3xxRedirection())
        .andExpect(org.springframework.test.web.servlet.result.MockMvcResultMatchers
            .redirectedUrl("/run/complete?create=true"));
    String accountCreationPage = mvc.perform(get("/run/complete").session(session)
        .param("create", "true"))
        .andExpect(status().isOk())
        .andExpect(content().string(containsString("Create Account &amp; Save Run")))
        .andExpect(content().string(containsString("Your Account ID will be:")))
        .andReturn()
        .getResponse()
        .getContentAsString();
    int reservedPlayerId = jdbcTemplate.queryForObject(
        "SELECT player_id FROM ACCOUNT_RESERVATION",
        Integer.class);
    assertTrue(accountCreationPage.contains("Your Account ID will be: <strong>"
        + reservedPlayerId + "</strong>"));
    mvc.perform(post("/account/create").session(session).param("password", "weakpassword"))
        .andExpect(status().is3xxRedirection())
        .andExpect(org.springframework.test.web.servlet.result.MockMvcResultMatchers
            .redirectedUrl("/run/complete?create=true&passwordError=true"));
    mvc.perform(get("/run/complete").session(session)
        .param("create", "true").param("passwordError", "true"))
        .andExpect(status().isOk())
        .andExpect(content().string(containsString("uppercase letter")));
    mvc.perform(post("/account/create").session(session).param("password", "SecurePass9!"))
        .andExpect(status().is3xxRedirection())
        .andExpect(redirectedUrlPattern("/run/complete?playerId=*&saved=true"));

    int playerId = jdbcTemplate.queryForObject(
        "SELECT player_id FROM PLAYER",
        Integer.class);
    assertEquals(reservedPlayerId, playerId);
    assertEquals(0, jdbcTemplate.queryForObject(
        "SELECT COUNT(*) FROM ACCOUNT_RESERVATION WHERE player_id = ?",
        Integer.class,
        playerId));
    assertEquals(1, jdbcTemplate.queryForObject(
        "SELECT COUNT(*) FROM RUN WHERE player_id = ?",
        Integer.class,
        playerId));
    assertTrue(accountService.authenticate(playerId, "SecurePass9!"));
    mvc.perform(get("/run/complete").session(session).param("playerId", String.valueOf(playerId)))
        .andExpect(status().isOk())
        .andExpect(content().string(not(containsString("Your Account ID is"))));
    mvc.perform(get("/login").session(session))
        .andExpect(status().isOk())
        .andExpect(content().string(containsString(
            "Your Account ID will be: <strong>" + playerId + "</strong>")));
    mvc.perform(get("/run/complete").session(session))
        .andExpect(status().isOk())
        .andExpect(content().string(containsString("Player ID: " + playerId)))
        .andExpect(content().string(containsString("Log Out")));
    mvc.perform(post("/logout").session(session))
        .andExpect(status().is3xxRedirection());
    mvc.perform(get("/").session(session))
        .andExpect(status().isOk())
        .andExpect(content().string(containsString("Log In")))
        .andExpect(content().string(not(containsString("Player ID: " + playerId))));
  }

  @Test
  void createsAccountWithoutRunFromStandaloneForm() throws Exception {
    MvcResult createPageResult = mvc.perform(get("/account/create"))
        .andExpect(status().isOk())
        .andExpect(content().string(containsString("Create Account")))
        .andExpect(content().string(containsString("Your Account ID will be:")))
        .andReturn();
    String createPage = createPageResult.getResponse().getContentAsString();
    MockHttpSession session = (MockHttpSession) createPageResult.getRequest().getSession(false);
    int reservedPlayerId = jdbcTemplate.queryForObject(
        "SELECT player_id FROM ACCOUNT_RESERVATION",
        Integer.class);
    assertTrue(createPage.contains("Your Account ID will be: <strong>"
        + reservedPlayerId + "</strong>"));
    mvc.perform(post("/account/create").session(session).param("password", "Standalone9!"))
        .andExpect(status().is3xxRedirection())
        .andExpect(redirectedUrlPattern("/account/created?playerId=*"));

    int playerId = jdbcTemplate.queryForObject(
        "SELECT player_id FROM PLAYER",
        Integer.class);
    assertEquals(reservedPlayerId, playerId);
    assertTrue(accountService.authenticate(playerId, "Standalone9!"));
    assertEquals(0, jdbcTemplate.queryForObject(
        "SELECT COUNT(*) FROM RUN WHERE player_id = ?",
        Integer.class,
        playerId));
    mvc.perform(get("/account/created").param("playerId", String.valueOf(playerId)))
        .andExpect(status().isOk())
        .andExpect(content().string(containsString("Your Account ID will be:")))
        .andExpect(content().string(containsString(String.valueOf(playerId))));
  }

  @Test
  void rejectsPasswordsMissingAnyRequiredCharacterType() throws Exception {
    String[] invalidPasswords = {
        "lowercase9!", "UPPERCASE9!", "NoNumber!!", "NoSpecial9", "Short1!"
    };

    for (String password : invalidPasswords) {
      mvc.perform(post("/account/create").param("password", password))
          .andExpect(status().is3xxRedirection())
          .andExpect(org.springframework.test.web.servlet.result.MockMvcResultMatchers
              .redirectedUrl("/account/create?error=true"));
    }

    assertEquals(0, jdbcTemplate.queryForObject("SELECT COUNT(*) FROM PLAYER", Integer.class));
    mvc.perform(get("/account/create").param("error", "true"))
        .andExpect(status().isOk())
        .andExpect(content().string(containsString("uppercase letter")));
  }

  @Test
  void deletesAccountButKeepsAnonymousRunAndInventory() {
    int playerId = accountService.createAccountAndSaveRun(
        "deletion passphrase",
        60,
        200,
        false,
        new int[] {1, 0, 0, 0});
    int runId = jdbcTemplate.queryForObject(
        "SELECT run_id FROM RUN WHERE player_id = ?",
        Integer.class,
        playerId);

    accountService.deleteAccount(playerId);

    assertEquals(0, jdbcTemplate.queryForObject(
        "SELECT COUNT(*) FROM PLAYER WHERE player_id = ?",
        Integer.class,
        playerId));
    assertEquals(1, jdbcTemplate.queryForObject(
        "SELECT COUNT(*) FROM RUN WHERE run_id = ? AND player_id IS NULL",
        Integer.class,
        runId));
    assertEquals(1, jdbcTemplate.queryForObject(
        "SELECT amount FROM GAINED_ITEM WHERE run_id = ? AND item_id = 1",
        Integer.class,
        runId));
    assertFalse(accountService.authenticate(playerId, "deletion passphrase"));
  }

  @Test
  void deleteFormRequiresValidCredentialsAndConfirmation() throws Exception {
    int playerId = accountService.createAccountAndSaveRun(
        "deletion passphrase",
        60,
        200,
        false,
        new int[] {0, 0, 0, 0});

    mvc.perform(post("/delete")
        .param("playerId", String.valueOf(playerId))
        .param("password", "deletion passphrase"))
        .andExpect(status().is3xxRedirection())
        .andExpect(org.springframework.test.web.servlet.result.MockMvcResultMatchers
            .redirectedUrl("/delete?error=true"));
    mvc.perform(post("/delete")
        .param("playerId", String.valueOf(playerId))
        .param("password", "deletion passphrase")
        .param("confirmDelete", "true"))
        .andExpect(status().is3xxRedirection())
        .andExpect(org.springframework.test.web.servlet.result.MockMvcResultMatchers
            .redirectedUrl("/delete?deleted=true"));
    mvc.perform(get("/delete").param("deleted", "true"))
        .andExpect(status().isOk())
        .andExpect(content().string(containsString("Account deleted. Run history has been retained")));
  }

  @Test
  void loggingIntoExistingAccountAddsTheCurrentRun() throws Exception {
    int playerId = accountService.createAccountAndSaveRun(
        "existing account passphrase",
        80,
        150,
        true,
        new int[] {0, 0, 0, 0});
    MvcResult completedRun = mvc.perform(post("/start/room-selection").param("option", "3"))
        .andExpect(status().is3xxRedirection())
        .andReturn();
    MockHttpSession session = (MockHttpSession) completedRun.getRequest().getSession(false);

    mvc.perform(post("/login")
        .session(session)
        .param("playerId", String.valueOf(playerId))
        .param("password", "existing account passphrase")
        .param("runComplete", "true"))
        .andExpect(status().is3xxRedirection())
        .andExpect(org.springframework.test.web.servlet.result.MockMvcResultMatchers
            .redirectedUrl("/run/complete?saved=true"));

    assertEquals(2, jdbcTemplate.queryForObject(
        "SELECT number_of_runs FROM PLAYER WHERE player_id = ?",
        Integer.class,
        playerId));
    assertEquals(2, jdbcTemplate.queryForObject(
        "SELECT COUNT(*) FROM RUN WHERE player_id = ?",
        Integer.class,
        playerId));
  }
