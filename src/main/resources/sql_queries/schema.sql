
-- player table
CREATE TABLE PLAYER (
    player_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password_hash VARCHAR(255) NOT NULL,
    number_of_runs INTEGER NOT NULL DEFAULT 0,
    high_score_run_id INTEGER UNIQUE
);

-- run table
CREATE TABLE RUN (
    run_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id INTEGER NOT NULL,
    steps INTEGER NOT NULL,
    score INTEGER NOT NULL,
    korokorobi BOOLEAN,
    CONSTRAINT uq_run_player_run UNIQUE (player_id, run_id),
    CONSTRAINT fk_run_player
        FOREIGN KEY (player_id) REFERENCES PLAYER(player_id)
);

-- add highscore key to player.
ALTER TABLE PLAYER
    ADD CONSTRAINT fk_player_high_score_run
    FOREIGN KEY (player_id, high_score_run_id)
    REFERENCES RUN(player_id, run_id);

-- NOTE: there are two relationships between PLAYER and RUN. A 1-1 "highscore" relationship, and a 1-N "ran" relationship

-- item table
CREATE TABLE ITEM (
    item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name VARCHAR(16),
    item_desc TEXT,
    item_icon VARCHAR(16),
    item_score INTEGER NOT NULL
);

-- monster table
CREATE TABLE MONSTER (
    monster_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monster_name VARCHAR(16),
    monster_desc TEXT,
    monster_icon VARCHAR(64),
    monster_score INTEGER NOT NULL
);

-- items gained table: N-M relationship between run and items
CREATE TABLE GAINED_ITEM (
    item_id INTEGER NOT NULL,
    run_id INTEGER NOT NULL,
    amount INTEGER NOT NULL,
    CONSTRAINT pk_gained_item PRIMARY KEY (item_id, run_id),
    CONSTRAINT fk_gained_item_item
        FOREIGN KEY (item_id) REFERENCES ITEM(item_id),
    CONSTRAINT fk_gained_item_run
        FOREIGN KEY (run_id) REFERENCES RUN(run_id)
);

-- monster gained table: N-M relationship between run and monster
CREATE TABLE GAINED_MONSTER (
    monster_id INTEGER NOT NULL,
    run_id INTEGER NOT NULL,
    amount INTEGER NOT NULL,
    CONSTRAINT pk_gained_monster PRIMARY KEY (monster_id, run_id),
    CONSTRAINT fk_gained_monster_monster
        FOREIGN KEY (monster_id) REFERENCES MONSTER(monster_id),
    CONSTRAINT fk_gained_monster_run
        FOREIGN KEY (run_id) REFERENCES RUN(run_id)
)