
-- player table
-- IF NOT EXISTS lets setup reapply this schema without replacing existing player data.
CREATE TABLE IF NOT EXISTS PLAYER (
    player_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password_hash VARCHAR(255) NOT NULL,
    number_of_runs INTEGER NOT NULL DEFAULT 0,
    high_score_run_id INTEGER UNIQUE
);

CREATE TABLE IF NOT EXISTS ACCOUNT_RESERVATION (
    player_id INTEGER PRIMARY KEY,
    reservation_token VARCHAR(36) NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_account_reservation_player
        FOREIGN KEY (player_id) REFERENCES PLAYER(player_id) ON DELETE CASCADE
);

-- run table
-- IF NOT EXISTS lets setup create newly added tables in databases initialized earlier.
CREATE TABLE IF NOT EXISTS RUN (
    run_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id INTEGER,
    steps INTEGER NOT NULL,
    score INTEGER NOT NULL,
    korokorobi BOOLEAN,
    CONSTRAINT uq_run_player_run UNIQUE (player_id, run_id),
    CONSTRAINT fk_run_player
        FOREIGN KEY (player_id) REFERENCES PLAYER(player_id)
);

-- add highscore key to player.
-- Check the catalog before adding this relationship so schema.sql can run repeatedly.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_player_high_score_run'
          AND conrelid = 'player'::regclass
    ) THEN
        ALTER TABLE PLAYER
            ADD CONSTRAINT fk_player_high_score_run
            FOREIGN KEY (player_id, high_score_run_id)
            REFERENCES RUN(player_id, run_id);
    END IF;
END
$$;

-- NOTE: there are two relationships between PLAYER and RUN. A 1-1 "highscore" relationship, and a 1-N "ran" relationship

-- item table
-- IF NOT EXISTS prevents recreating the existing catalog table.
CREATE TABLE IF NOT EXISTS ITEM (
    item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name VARCHAR(16),
    item_desc TEXT,
    item_icon VARCHAR(16),
    item_score INTEGER NOT NULL
);

-- monster table
-- IF NOT EXISTS prevents recreating the existing catalog table.
CREATE TABLE IF NOT EXISTS MONSTER (
    monster_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monster_name VARCHAR(16),
    monster_desc TEXT,
    monster_icon VARCHAR(64),
    monster_score INTEGER NOT NULL
);

-- items gained table: N-M relationship between run and items
-- IF NOT EXISTS lets this table be added to previously initialized databases.
CREATE TABLE IF NOT EXISTS GAINED_ITEM (
    item_id INTEGER NOT NULL,
    run_id INTEGER NOT NULL,
    amount INTEGER NOT NULL,
    CONSTRAINT pk_gained_item PRIMARY KEY (item_id, run_id),
    CONSTRAINT fk_gained_item_item
        FOREIGN KEY (item_id) REFERENCES ITEM(item_id),
    CONSTRAINT fk_gained_item_run
        FOREIGN KEY (run_id) REFERENCES RUN(run_id)
);

-- monster gained table: N-M relationship between run and monster
-- IF NOT EXISTS lets this table be added to previously initialized databases.
CREATE TABLE IF NOT EXISTS GAINED_MONSTER (
    monster_id INTEGER NOT NULL,
    run_id INTEGER NOT NULL,
    amount INTEGER NOT NULL,
    CONSTRAINT pk_gained_monster PRIMARY KEY (monster_id, run_id),
    CONSTRAINT fk_gained_monster_monster
        FOREIGN KEY (monster_id) REFERENCES MONSTER(monster_id),
    CONSTRAINT fk_gained_monster_run
        FOREIGN KEY (run_id) REFERENCES RUN(run_id)
);

-- monster / monster interaction
-- IF NOT EXISTS creates combat support in older databases without touching existing rows.
CREATE TABLE IF NOT EXISTS MONSTER_MONSTER (
    -- key attributes
    enemy_monster INTEGER NOT NULL,
    player_monster INTEGER NOT NULL,
    current_state CHAR NOT NULL,
    -- effect attributes
    result TEXT, -- describes what happened
    new_state CHAR, -- NULL if state did not change
    lose BOOLEAN, -- If player_monster gets removed, attribute is TRUE
    -- foreign/primary key declaration
    CONSTRAINT pk_monster_monster PRIMARY KEY (enemy_monster, player_monster, current_state),
    CONSTRAINT fk_monster_monster_enemy
        FOREIGN KEY (enemy_monster) REFERENCES MONSTER(monster_id),
    CONSTRAINT fk_monster_monster_player
        FOREIGN KEY (player_monster) REFERENCES MONSTER(monster_id)
);

-- monster / item interaction
-- IF NOT EXISTS creates combat support in older databases without touching existing rows.
CREATE TABLE IF NOT EXISTS MONSTER_ITEM (
    -- key attributes
    enemy_monster INTEGER NOT NULL,
    player_item INTEGER NOT NULL,
    current_state CHAR NOT NULL,
    -- effect attributes
    result TEXT, -- describes what happened
    new_state CHAR, -- NULL if state did not change
    lose BOOLEAN, -- If player_item gets removed, attribute is TRUE
    -- foreign/primary key declaration
    CONSTRAINT pk_item_monster PRIMARY KEY (enemy_monster, player_item, current_state),
    CONSTRAINT fk_item_monster_enemy
        FOREIGN KEY (enemy_monster) REFERENCES MONSTER(monster_id),
    CONSTRAINT fk_item_monster_item
        FOREIGN KEY (player_item) REFERENCES ITEM(item_id)
);